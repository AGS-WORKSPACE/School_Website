function account(
  id: string,
  personId: string,
  username: string,
  options: Partial<Account> = {},
): Account {
  return {
    id,
    personId,
    username,
    status: "active",
    statusReason: null,
    mfaEnrolments: [],
    recoveryCodes: null,
    lastSignInAt: at(-120),
    createdAt: at(-days(700)),
    updatedAt: at(-days(30)),
    ...options,
  };
}

function totp(accountId: string, label: string, enrolledDaysAgo: number) {
  return {
    id: `mfa-${accountId}-totp`,
    accountId,
    kind: "totp" as const,
    label,
    status: "active" as const,
    enrolledAt: at(-days(enrolledDaysAgo)),
    lastUsedAt: at(-180),
  };
}

function recoveryBatch(accountId: string, used: number, total = 10) {
  return {
    id: `rec-${accountId}`,
    accountId,
    issuedAt: at(-days(120)),
    issuedBy: "per-tunde",
    codes: Array.from({ length: total }, (_, index) => ({
      id: `${accountId}-code-${index + 1}`,
      usedAt: index < used ? at(-days(30 - index)) : null,
    })),
  };
}

